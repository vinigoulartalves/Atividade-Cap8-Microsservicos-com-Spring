CREATE TABLE usuarios (
    id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR2(120) NOT NULL,
    email VARCHAR2(180) NOT NULL UNIQUE,
    senha VARCHAR2(255) NOT NULL,
    role VARCHAR2(20) NOT NULL,
    data_criacao TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL
);

CREATE TABLE denuncias (
    id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    titulo VARCHAR2(150) NOT NULL,
    descricao VARCHAR2(1000) NOT NULL,
    endereco VARCHAR2(255) NOT NULL,
    bairro VARCHAR2(120) NOT NULL,
    cidade VARCHAR2(120) NOT NULL,
    estado VARCHAR2(2) NOT NULL,
    latitude NUMBER(10, 7) NOT NULL,
    longitude NUMBER(10, 7) NOT NULL,
    categoria_residuo VARCHAR2(40) NOT NULL,
    status VARCHAR2(30) NOT NULL,
    usuario_id NUMBER NOT NULL,
    data_criacao TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    data_atualizacao TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT fk_denuncias_usuario FOREIGN KEY (usuario_id) REFERENCES usuarios(id)
);

CREATE OR REPLACE TRIGGER trg_denuncias_data_atualizacao
BEFORE UPDATE ON denuncias
FOR EACH ROW
BEGIN
    :NEW.data_atualizacao := CURRENT_TIMESTAMP;
END;
/
